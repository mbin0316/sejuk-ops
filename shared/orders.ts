// Order domain shared by the React app (src/) and the API (server/):
// statuses, service types, request validation and the JSON shapes the API returns.
// One definition, so the form and the server can't drift apart.
import { z } from 'zod'

/** Workflow: New → Assigned → In Progress → Job Done → Reviewed → Closed */
export const ORDER_STATUSES = ['new', 'assigned', 'in_progress', 'job_done', 'reviewed', 'closed'] as const
export type OrderStatus = (typeof ORDER_STATUSES)[number]

/** Statuses in which the admin may still (re)assign the technician. */
export const ASSIGNABLE_STATUSES: readonly OrderStatus[] = ['new', 'assigned']

/** Service type dropdown (Admin portal). Must match the check constraint in supabase/schema.sql. */
export const SERVICE_TYPES = [
  'Installation',
  'General servicing',
  'Chemical wash',
  'Repair',
  'Gas top-up',
  'Inspection',
] as const
export type ServiceType = (typeof SERVICE_TYPES)[number]

/** Loose phone check: optional +, then 6–20 digits, spaces or dashes. */
const PHONE_RE = /^\+?[0-9][0-9 -]{5,19}$/

export const money = (label: string) =>
  z
    .number({ error: `Enter the ${label}` })
    .min(0, `The ${label} can't be negative`)
    .max(1_000_000, `The ${label} looks too high`)
    .refine((v) => Math.abs(Math.round(v * 100) - v * 100) < 1e-6, 'Use at most 2 decimal places')

/** POST /api/orders body. Order No is generated by the database. */
export const createOrderSchema = z.object({
  customerName: z.string().trim().min(1, 'Enter the customer name').max(120, 'Keep the name under 120 characters'),
  customerPhone: z.string().trim().regex(PHONE_RE, 'Enter a valid phone number, e.g. 012-345 6789'),
  customerAddress: z.string().trim().min(1, 'Enter the service address').max(300, 'Keep the address under 300 characters'),
  problemDescription: z
    .string()
    .trim()
    .min(1, 'Describe the problem')
    .max(1000, 'Keep the description under 1,000 characters'),
  serviceType: z.enum(SERVICE_TYPES, { error: 'Choose a service type' }),
  quotedPrice: money('quoted price'),
  technicianId: z.number().int().positive().nullable(),
  adminNotes: z.string().trim().max(1000, 'Keep notes under 1,000 characters').optional(),
})
export type CreateOrderInput = z.infer<typeof createOrderSchema>

/** POST /api/orders/:id/review and /close body: optional note for the history. */
export const reviewNoteSchema = z.object({
  note: z.string().trim().max(500, 'Keep the note under 500 characters').optional(),
})
export type ReviewNoteInput = z.infer<typeof reviewNoteSchema>

/** POST /api/orders/:id/assign body. */
export const assignSchema = z.object({ technicianId: z.number().int().positive() })

// ---------------------------------------------------------------------------
// API response shapes (camelCase JSON)
// ---------------------------------------------------------------------------
export type Technician = { id: number; name: string; phone: string; active: boolean }

export type OrderListItem = {
  id: string
  orderNo: string
  customerName: string
  customerPhone: string
  customerAddress: string
  serviceType: ServiceType
  quotedPrice: number
  status: OrderStatus
  technician: { id: number; name: string } | null
  createdAt: string
  completedAt: string | null
}

export type JobReport = {
  technicianName: string
  workDone: string
  extraCharges: number
  finalAmount: number
  remarks: string | null
  paymentAmount: number | null
  paymentMethod: string | null
  completedAt: string
}

/** Uploaded job file. `url` is a short-lived signed download link (private bucket). */
export type Attachment = {
  id: string
  name: string
  type: string
  size: number
  url: string | null
  uploadedBy: string
  createdAt: string
}

export type OrderEvent = {
  id: number
  action: string
  fromStatus: OrderStatus | null
  toStatus: OrderStatus | null
  actorName: string
  actorRole: string
  details: Record<string, unknown>
  createdAt: string
}

export type OrderDetail = Omit<OrderListItem, 'technician'> & {
  problemDescription: string
  adminNotes: string | null
  createdBy: string
  rescheduleCount: number
  assignedAt: string | null
  startedAt: string | null
  reviewedAt: string | null
  reviewedBy: string | null
  closedAt: string | null
  technician: Technician | null
  report: JobReport | null
  attachments: Attachment[]
  events: OrderEvent[]
}

/** A job in the manager's review queue (GET /api/review). */
export type ReviewItem = OrderListItem & {
  rescheduleCount: number
  reviewedAt: string | null
  reviewedBy: string | null
  report: JobReport | null
  attachmentCount: number
}

export type ReviewQueue = {
  /** Job done, waiting for manager review: oldest completion first. */
  waiting: ReviewItem[]
  /** Reviewed, waiting to be closed: oldest review first. */
  toClose: ReviewItem[]
}

// ---------------------------------------------------------------------------
// WhatsApp (wa.me deep links)
// ---------------------------------------------------------------------------

/** "012-345 6789" → "60123456789" (Malaysian local numbers get the 60 country code). */
export function toWhatsAppNumber(phone: string) {
  const digits = phone.replace(/\D/g, '')
  if (digits.startsWith('60')) return digits
  if (digits.startsWith('0')) return `6${digits}`
  return digits
}

export function whatsAppLink(phone: string, message: string) {
  return `https://wa.me/${toWhatsAppNumber(phone)}?text=${encodeURIComponent(message)}`
}
